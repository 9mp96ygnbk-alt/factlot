export interface ChartSection {
  id: string;
  label: string;
}

export interface ChartCategory {
  id: string;
  label: string;
  section: string;
  /** Always subtracted from its section, whatever sign the statement writes (vacancy, concessions). */
  contra?: boolean;
  /** "memo" categories are statistics, not summed; ratio ones accept 95% for 0.95. */
  ratio?: boolean;
  keywords: readonly string[];
}

export interface ChartTotal {
  id: string;
  label: string;
  /** Section ids or earlier total ids; a leading "-" subtracts. */
  sum: readonly string[];
  keywords: readonly string[];
}

export interface Chart {
  label: string;
  sections: readonly ChartSection[];
  categories: readonly ChartCategory[];
  totals: readonly ChartTotal[];
}

