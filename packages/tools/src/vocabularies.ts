/**
 * Open vocabularies the document tools match against: a use-category vocabulary for
 * doc_check_use_conflict and a chart of accounts for doc_spread_statement. This file is the
 * source; `npm run schemas` writes both to spec/schemas/vocabularies/*.json, which the Python SDK
 * reads, so the two languages match on the same data.
 *
 * Keywords are matched as whole words after the normalization in `words()` (documents.ts):
 * lower case, accents removed, punctuation as spaces, simple plurals folded ("bakeries" →
 * "bakery"). Where two keywords of different categories overlap, the longer one wins, so "juice
 * bar" is a juice bar and not a bar. NAICS codes are 2022 NAICS, listed only where a code
 * clearly covers the category.
 */

export interface UseCategory {
  id: string;
  label: string;
  keywords: readonly string[];
  naics?: readonly string[];
}

