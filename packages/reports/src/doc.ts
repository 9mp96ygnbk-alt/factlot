/**
 * The neutral document model every report kind builds, and its two renderings: a PDF (flowing
 * pages) and an XLSX workbook (a Report sheet, one sheet per long table, a Checks sheet with live
 * formulas that tie the figures out, and a ReadMe). A kind can replace the workbook with its own
 * (tx_unequal_appraisal does, to mirror the reconciliation example).
 */
import { int, num, pct, sig, times, usd } from "./format.ts";
// pdf.ts (and pdf-lib) load on the first PDF only: an XLSX or ICS request never evaluates them.
import { PdfWriter, WIDE_TABLE_COLUMNS, type Column } from "./pdf.ts";
import {
  Workbook,
  addr,
  excelSerial,
  fx,
  range,
  type Sheet,
  type Style,
} from "./xlsx.ts";

/**
 * How a value is written (format.ts has the convention): usd to the cent, pct a percentage to
 * 2 decimals (pct4: 4), times a ratio to 2, int a grouped whole number, plain a number as is
 * with no grouping (years, periods, counts), exact a number as sent (grouped), factor at least 4 decimals, num (and step) a
 * number to 6 significant digits.
 */
export type Fmt =
  | "usd"
  | "num"
  | "num4"
  | "factor"
  | "step"
  | "int"
  | "plain"
  | "exact"
  | "pct"
  | "pct4"
  | "times"
  | "text"
  | "date";
export type Raw = number | string | null;

export interface Kv {
  label: string;
  value: Raw;
  fmt: Fmt;
  note?: string;
  /** Names the cell for check formulas: {name}. */
  name?: string;
}

export interface TableColumn {
  header: string;
  fmt: Fmt;
  /** Relative width (PDF share of the page, XLSX column width / 10). */
  width?: number;
  /** Names the column's data range for check formulas: {name}. */
  name?: string;
}

export type Block = BlockBody & {
  /** Render in one format only. */
  only?: "pdf" | "xlsx";
};

type BlockBody =
  | { t: "heading"; text: string }
  | { t: "subheading"; text: string }
  | { t: "para"; text: string; grey?: boolean }
  | { t: "notice"; text: string; tone?: "warn" | "info" }
  | { t: "bullets"; items: string[] }
  | { t: "kv"; rows: Kv[] }
  | {
      t: "table";
      columns: TableColumn[];
      rows: Raw[][];
      /** Rows drawn in bold (totals, the median). */
      bold?: number[];
      /** Put the table on its own workbook sheet with this name. */
      sheet?: string;
      /** PDF text size. */
      size?: number;
      /** Per-cell formats overriding the column's, by row then column. */
      fmts?: (Fmt | undefined)[][];
    }
  | { t: "pagebreak" };

/** A live check for the workbook: an Excel formula over named cells against FactLot's figure. */
export interface Check {
  label: string;
  /** Excel formula with {name} placeholders, e.g. "{pv_cf}+{pv_rev}" or "SUM({interest})". */
  formula: string;
  factlot: number;
  /** Decimals the difference is rounded to. */
  dp: number;
  field: string;
}

export interface ReportDoc {
  title: string;
  subtitle: string;
  blocks: Block[];
  checks?: Check[];
  /** ReadMe lines for the workbook (what it is, how to read it). */
  readme: string[];
}

export interface Provenance {
  /** "Generated by FactLot ... see https://factlot.com/terms" */
  footer: string;
  version: string;
  /** e.g. calc_debt_sizing@3 */
  toolRef: string;
  generatedAt: Date;
  /** Short report name for the page header. */
  header: string;
  keywords: string[];
}

// --- PDF ----------------------------------------------------------------------------------------

export function fmtText(v: Raw, fmt: Fmt): string {
  if (v === null || v === undefined) return "";
  if (typeof v === "string") return v;
  switch (fmt) {
    case "usd":
      return usd(v);
    case "pct":
      return pct(v);
    case "pct4":
      return pct(v, 4);
    case "times":
      return times(v);
    case "int":
      return Number.isInteger(v) ? int(v) : sig(v);
    case "plain":
      return String(v);
    case "exact":
      return num(v);
    case "num4":
      return num(v, 2);
    case "factor":
      return num(v, 4);
    default:
      return sig(v);
  }
}

const RIGHT: ReadonlySet<Fmt> = new Set([
  "usd",
  "num",
  "num4",
  "factor",
  "step",
  "int",
  "plain",
  "exact",
  "pct",
  "pct4",
  "times",
]);

export async function renderPdf(
  doc: ReportDoc,
  p: Provenance,
): Promise<Uint8Array> {
  const w = await PdfWriter.create({
    title: doc.title,
    subject: doc.subtitle,
    header: p.header,
    footer: p.footer,
    producer: `FactLot ${p.version} reports`,
    keywords: p.keywords,
    created: p.generatedAt,
  });
  w.title(doc.title, doc.subtitle);
  const blocks = doc.blocks.filter((b) => b.only !== "xlsx");
  // A wide table goes on landscape pages, with the heading and text that introduce it; what
  // follows returns to portrait.
  const land: boolean[] = [];
  let carry = false;
  for (let i = blocks.length - 1; i >= 0; i--) {
    const b = blocks[i]!;
    if (b.t === "table" || b.t === "kv" || b.t === "pagebreak")
      carry = b.t === "table" && b.columns.length > WIDE_TABLE_COLUMNS;
    land[i] = carry;
    if (b.t === "heading") carry = false;
  }
  for (const [i, b] of blocks.entries()) {
    w.orientation(land[i]!);
    switch (b.t) {
      case "heading":
        w.heading(b.text);
        break;
      case "subheading":
        w.subheading(b.text);
        break;
      case "para":
        w.para(b.text, { color: b.grey ? "grey" : "ink" });
        break;
      case "notice":
        w.notice(b.text, b.tone ?? "warn");
        break;
      case "bullets":
        w.bullets(b.items);
        break;
      case "kv":
        w.kv(
          b.rows.map((r) => [
            r.note ? `${r.label} (${r.note})` : r.label,
            fmtText(r.value, r.fmt),
          ]),
        );
        break;
      case "table": {
        const cols: Column[] = b.columns.map((c) => ({
          header: c.header,
          width: c.width ?? 1,
          align: RIGHT.has(c.fmt) ? "right" : "left",
        }));
        w.table(
          cols,
          b.rows.map((r, k) =>
            r.map((v, i) => fmtText(v, b.fmts?.[k]?.[i] ?? b.columns[i]!.fmt)),
          ),
          { size: b.size ?? 8, bold: new Set(b.bold ?? []) },
        );
        break;
      }
      case "pagebreak":
        w.pageBreak();
        break;
    }
  }
  return w.bytes();
}

// --- XLSX ---------------------------------------------------------------------------------------

/** The cell style for a value of a format. */
export function styleFor(v: Raw, fmt: Fmt): Style {
  if (typeof v === "string" || v === null)
    return fmt === "date" && v ? "date" : "text";
  switch (fmt) {
    case "usd":
      return "money";
    case "int":
      return Number.isInteger(v) ? "int" : "num_s";
    case "plain":
    case "exact":
      return "default";
    case "pct":
      return "pct2";
    case "pct4":
      return "pct4";
    case "times":
      return "times";
    case "num4":
    case "factor":
      return "num4";
    default:
      return Number.isInteger(v) ? "int" : "num_s";
  }
}

/** The value as stored: ISO dates become Excel dates. */
export function cellValue(v: Raw, fmt: Fmt): number | string | null {
  if (fmt === "date" && typeof v === "string" && /^\d{4}-\d{2}-\d{2}$/.test(v))
    return excelSerial(v);
  return v;
}

const FL_STYLE: Partial<Record<Style, Style>> = {
  money: "fl_money",
  num4: "fl_num4",
  num6: "fl_num6",
  num8: "fl_num8",
  pct2: "fl_pct4",
  pct4: "fl_pct4",
  pct6: "fl_num8",
  int: "fl_int",
  default: "fl_num8",
  num_s: "fl_num8",
  times: "fl_num4",
};

export function putLines(
  sh: Sheet,
  row: number,
  lines: string[],
  style: Style = "text",
  col = 1,
): number {
  for (const l of lines) sh.put(row++, col, l, style);
  return row;
}

/** ReadMe sheet shared by the generic workbooks. */
function readmeSheet(
  wb: Workbook,
  doc: ReportDoc,
  p: Provenance,
  notices: string[],
  hasChecks: boolean,
): void {
  const sh = wb.sheet("ReadMe");
  sh.width(1, 120);
  sh.put(1, 1, doc.title, "title");
  let r = 2;
  for (const n of notices) sh.put(r++, 1, n, "warn");
  r++;
  sh.put(r++, 1, "What this workbook is", "bold");
  r = putLines(sh, r, doc.readme);
  r++;
  sh.put(r++, 1, "How to read it", "bold");
  const hasSteps = doc.blocks.some(
    (b) => b.t === "table" && b.sheet === "Steps",
  );
  r = putLines(sh, r, [
    "Report: the figures as the tool returned them, formatted. Long tables (schedules, cash flows, events) have their own sheets.",
    ...(hasSteps
      ? [
          "Steps: the tool's audit trail, each step's value and how it was reached.",
        ]
      : []),
    ...(hasChecks
      ? [
          "Checks: live Excel formulas over the Report figures next to the number FactLot returned, with a Difference column and a Status. Difference is ROUND(Excel - FactLot, n); 0 means they agree.",
        ]
      : []),
  ]);
  r++;
  sh.put(
    r++,
    1,
    `FactLot version ${p.version}. Tool and formula: ${p.toolRef}`,
    "bold",
  );
  sh.put(r, 1, p.footer, "note");
}

/**
 * Write blocks down a sheet from row `r` (headings, text, label/value rows, tables; a table
 * with a sheet name gets its own sheet). Named cells and ranges go into `names`. Returns the
 * next free row.
 */
export function appendBlocks(
  wb: Workbook,
  main: Sheet,
  start: number,
  blocks: Block[],
  title: string,
  names: Map<string, string>,
): number {
  let r = start;
  const tableSheet = (
    b: Extract<Block, { t: "table" }>,
    sh: Sheet,
    start: number,
  ): number => {
    let row = start;
    b.columns.forEach((c, i) => {
      sh.put(row, i + 1, c.header, "header");
      const w = Math.max(10, Math.min(60, (c.width ?? 1) * 14));
      if (sh !== main || i > 2) sh.width(i + 1, w);
    });
    if (sh !== main) sh.freeze = `A${row + 1}`;
    row++;
    const first = row;
    const bold = new Set(b.bold ?? []);
    b.rows.forEach((cells, k) => {
      cells.forEach((v, i) => {
        const fmt = b.fmts?.[k]?.[i] ?? b.columns[i]!.fmt;
        if (v === null || v === undefined) return;
        const st = styleFor(v, fmt);
        sh.put(
          row,
          i + 1,
          cellValue(v, fmt),
          bold.has(k) && st === "money"
            ? "total_money"
            : bold.has(k) && st === "text"
              ? "total_text"
              : st,
        );
      });
      row++;
    });
    b.columns.forEach((c, i) => {
      if (c.name && b.rows.length)
        names.set(
          c.name,
          range(
            `${sh.name}!${addr(first, i + 1, true)}`,
            `${sh.name}!${addr(row - 1, i + 1, true)}`,
          ),
        );
    });
    return row;
  };
  for (const b of blocks) {
    if (b.only === "pdf") continue;
    switch (b.t) {
      case "heading":
        r++;
        main.put(r++, 1, b.text, "bold");
        break;
      case "subheading":
        main.put(r++, 1, b.text, "bold");
        break;
      case "para":
        main.put(r++, 1, b.text, b.grey ? "note" : "text");
        break;
      case "notice":
        main.put(
          r++,
          1,
          b.text,
          (b.tone ?? "warn") === "warn" ? "warn" : "note",
        );
        break;
      case "bullets":
        for (const item of b.items) main.put(r++, 1, item, "text");
        break;
      case "kv":
        for (const kv of b.rows) {
          main.put(r, 1, kv.label, "text");
          if (kv.value !== null) {
            const ref = main.put(
              r,
              2,
              cellValue(kv.value, kv.fmt),
              styleFor(kv.value, kv.fmt),
            );
            if (kv.name) names.set(kv.name, ref);
          }
          if (kv.note) main.put(r, 3, kv.note, "note");
          r++;
        }
        break;
      case "table":
        if (b.sheet) {
          const sh = wb.sheet(b.sheet);
          sh.put(1, 1, `${title}: ${b.sheet.replace(/_/g, " ")}`, "title");
          tableSheet(b, sh, 3);
          main.put(
            r++,
            1,
            `See the ${b.sheet} sheet (${b.rows.length} rows).`,
            "note",
          );
        } else r = tableSheet(b, main, r) + 1;
        break;
      case "pagebreak":
        r++;
        break;
    }
  }
  return r;
}

/** A workbook from the generic model. */
export async function renderXlsx(
  doc: ReportDoc,
  p: Provenance,
): Promise<Uint8Array> {
  const wb = new Workbook({
    title: doc.title,
    creator: `FactLot ${p.version}`,
    created: p.generatedAt.toISOString().replace(/\.\d+Z$/, "Z"),
    footer: p.footer,
  });
  const notices = doc.blocks
    .filter((b) => b.t === "notice" && (b.tone ?? "warn") === "warn")
    .map((b) => (b as { text: string }).text);
  readmeSheet(wb, doc, p, notices, Boolean(doc.checks?.length));
  const main = wb.sheet("Report");
  main.width(1, 46);
  main.width(2, 22);
  main.width(3, 60);
  main.put(1, 1, doc.title, "title");
  main.put(2, 1, doc.subtitle, "note");
  const names = new Map<string, string>();
  appendBlocks(wb, main, 4, doc.blocks, doc.title, names);
  if (doc.checks?.length) {
    const sh = wb.sheet("Checks");
    [46, 22, 22, 14, 12, 40].forEach((w, i) => sh.width(i + 1, w));
    sh.put(1, 1, "Checks: live Excel formulas vs FactLot output", "title");
    sh.put(
      2,
      1,
      "Excel column = a live formula over the Report figures. FactLot column = the number the tool returned (recorded).",
      "note",
    );
    [
      "Output",
      "Excel (live formula)",
      "FactLot (recorded)",
      "Difference",
      "Status",
      "FactLot field",
    ].forEach((h, i) => sh.put(4, i + 1, h, "header"));
    let row = 5;
    for (const c of doc.checks) {
      const f = c.formula.replace(/\{([a-z0-9_]+)\}/g, (_, n: string) => {
        const ref = names.get(n);
        if (!ref) throw new Error(`check ${c.label}: no cell named ${n}`);
        return ref;
      });
      sh.put(row, 1, c.label, "text");
      const style = styleFor(
        c.factlot,
        Number.isInteger(c.factlot) || c.dp <= 2 ? "usd" : "num4",
      );
      sh.put(row, 2, fx(`=${f}`), style);
      sh.put(row, 3, c.factlot, FL_STYLE[style] ?? "fl_money");
      sh.put(
        row,
        4,
        fx(`=ROUND(${addr(row, 2)}-${addr(row, 3)},${c.dp})`),
        "diff",
      );
      sh.put(row, 5, fx(`=IF(${addr(row, 4)}=0,"match","DIFFERENT")`), "bold");
      sh.put(row, 6, c.field, "note");
      row++;
    }
    sh.freeze = "A5";
  }
  return wb.bytes();
}
