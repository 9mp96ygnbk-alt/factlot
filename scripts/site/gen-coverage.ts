// Writes site/_data/coverage-stores.json, the stores of the one coverage manifest (the build puts them
// in https://factlot.com/coverage.json): every published coverage figure, for
// each store (the hosted registry and the FactLot record), with the time it was computed and what it
// was computed from. The hosted registry's figures are copied from site/_data/hosted.json (the pack's
// manifest), never typed. The record's figures are read from the record's own stats endpoint.
//
//   node --experimental-strip-types scripts/site/gen-coverage.ts            refresh the hosted store, keep the record's
//   node --experimental-strip-types scripts/site/gen-coverage.ts --record   also read the record's figures now (network)
//   node --experimental-strip-types scripts/site/gen-coverage.ts --check    fail if the manifest is out of date
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../", import.meta.url));
export const COVERAGE_FILE = "site/_data/coverage-stores.json";
/** The hosted Worker states the stores from this generated module (it cannot read site/_data). */
export const STORES_MODULE = "deploy/cloudflare/src/coverage_stores.ts";
/** The page that states both stores in words, between the coverage:stores markers. */
export const COVERAGE_PAGE = "site/_content/coverage.html";
const OPEN = "<!-- coverage:stores -->";
const CLOSE = "<!-- /coverage:stores -->";
export const RECORD_STATS_URL =
  "https://czmyqwkauymguoznzpzr.supabase.co/functions/v1/app?op=stats";

export interface CoverageStore {
  id: "hosted_registry" | "record";
  name: string;
  describes: string;
  authoritative_for: string[];
  parcels: number;
  counties: number;
  states: number;
  /** When the figures were computed (ISO 8601, UTC). */
  computed_at: string;
  computed_from: string;
}
export interface CoverageManifest {
  about: string;
  generated_at: string;
  answer_first: string;
  stores: CoverageStore[];
  relation: string;
}

const read = (p: string): unknown =>
  JSON.parse(readFileSync(new URL(p, `file://${root}`), "utf8"));

/** The hosted store's figures as the pack manifest states them. */
export function hostedFigures(): Pick<
  CoverageStore,
  "parcels" | "counties" | "states" | "computed_at"
> {
  const h = read("site/_data/hosted.json") as {
    pack_built_at: string;
    totals: { parcels: number; counties: number; states: string[] };
  };
  return {
    parcels: h.totals.parcels,
    counties: h.totals.counties,
    states: h.totals.states.length,
    computed_at: h.pack_built_at,
  };
}

const n = (x: number): string => x.toLocaleString("en-US");
const day = (iso: string): string => iso.slice(0, 10);

/** The two stores in one plain paragraph, for the coverage page. */
export function storesText(m: CoverageManifest): string {
  const h = m.stores.find((s) => s.id === "hosted_registry")!;
  const r = m.stores.find((s) => s.id === "record")!;
  return `The tools answer from the hosted registry: ${n(h.parcels)} parcels in ${n(h.counties)} counties across ${n(h.states)} states, as built ${day(h.computed_at)}. These are the figures for what you can query today. The FactLot record, a separate store the tools do not answer from yet, held ${n(r.parcels)} parcels in ${n(r.counties)} counties across ${n(r.states)} states when read ${day(r.computed_at)}. Both figures, with their dates, are in <a href="/coverage.json">coverage.json</a>.`;
}

/** The page text with the stores paragraph set between its markers. */
export function renderStores(page: string, m: CoverageManifest): string {
  const a = page.indexOf(OPEN);
  const b = page.indexOf(CLOSE);
  if (a < 0 || b < a) throw new Error(`${COVERAGE_PAGE} has no ${OPEN} span`);
  return `${page.slice(0, a + OPEN.length)}${storesText(m)}${page.slice(b)}`;
}

/** The generated module the hosted Worker imports: the stores, and the store its registry tools answer from. */
export function storesModule(m: CoverageManifest): string {
  return `// Generated by scripts/site/gen-coverage.ts from ${COVERAGE_FILE}; do not edit.
export const COVERAGE_MANIFEST_URL = "https://factlot.com/coverage.json";
export const COVERAGE_STORES = ${JSON.stringify(m.stores, null, 2)} as const;
`;
}

const squash = (x: string): string => x.replace(/\s+/g, " ").trim();
/** Whether the page's stores paragraph says what the manifest gives (line breaks aside: the page is formatted). */
export function pageStatesStores(page: string, m: CoverageManifest): boolean {
  const a = page.indexOf(OPEN);
  const b = page.indexOf(CLOSE);
  return (
    a >= 0 &&
    b > a &&
    squash(page.slice(a + OPEN.length, b)) === squash(storesText(m))
  );
}

/** What differs between the manifest and the data it is generated from (empty: current). */
export function coverageDifferences(m: CoverageManifest): string[] {
  const out: string[] = [];
  const hosted = m.stores.find((s) => s.id === "hosted_registry");
  const record = m.stores.find((s) => s.id === "record");
  if (!hosted) return ["no hosted_registry store"];
  if (!record) out.push("no record store");
  for (const [k, v] of Object.entries(hostedFigures()))
    if (hosted[k as keyof CoverageStore] !== v)
      out.push(
        `hosted_registry.${k} is ${String(hosted[k as keyof CoverageStore])}; site/_data/hosted.json says ${String(v)}`,
      );
  const page = readFileSync(new URL(COVERAGE_PAGE, `file://${root}`), "utf8");
  if (record && !pageStatesStores(page, m))
    out.push(`${COVERAGE_PAGE} does not state the manifest's figures`);
  const mod = readFileSync(new URL(STORES_MODULE, `file://${root}`), "utf8");
  for (const st of m.stores)
    for (const v of [st.parcels, st.counties, st.states, st.computed_at])
      if (!mod.includes(JSON.stringify(v)))
        out.push(`${STORES_MODULE} does not hold ${st.id}'s ${String(v)}`);
  for (const s of m.stores) {
    if (!/^\d{4}-\d{2}-\d{2}T[\d:.]+Z$/.test(s.computed_at))
      out.push(`${s.id}.computed_at is not a UTC timestamp`);
    for (const k of ["parcels", "counties", "states"] as const)
      if (!Number.isInteger(s[k]) || s[k] <= 0)
        out.push(`${s.id}.${k} is not a positive whole number`);
  }
  return out;
}

async function recordFigures(): Promise<
  Pick<CoverageStore, "parcels" | "counties" | "states" | "computed_at">
> {
  const res = await fetch(RECORD_STATS_URL);
  const body = (await res.json()) as {
    ok?: boolean;
    result?: Record<string, string | number>;
  };
  if (!res.ok || !body.result)
    throw new Error(`record stats: HTTP ${res.status}`);
  const n = (k: string) => Number(body.result![k]);
  return {
    parcels: n("parcels"),
    counties: n("counties"),
    states: n("states"),
    // The record's own computed_at once it reports one (see docs/registry/coverage-unification.md);
    // until then, the time of this read.
    computed_at: String(
      body.result.computed_at ??
        new Date().toISOString().replace(/\.\d+Z$/, "Z"),
    ),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const m = read(COVERAGE_FILE) as CoverageManifest;
  if (process.argv.includes("--check")) {
    const d = coverageDifferences(m);
    if (d.length) {
      console.error(`${COVERAGE_FILE} is out of date:\n  ${d.join("\n  ")}`);
      process.exit(1);
    }
    console.log(`${COVERAGE_FILE} is current`);
  } else {
    const next: CoverageManifest = structuredClone(m);
    Object.assign(
      next.stores.find((s) => s.id === "hosted_registry")!,
      hostedFigures(),
    );
    if (process.argv.includes("--record"))
      Object.assign(
        next.stores.find((s) => s.id === "record")!,
        await recordFigures(),
      );
    if (JSON.stringify(next) !== JSON.stringify(m)) {
      next.generated_at = new Date().toISOString().replace(/\.\d+Z$/, "Z");
      writeFileSync(
        new URL(COVERAGE_FILE, `file://${root}`),
        `${JSON.stringify(next, null, 2)}\n`,
      );
      console.log(`wrote ${COVERAGE_FILE}`);
    } else console.log(`${COVERAGE_FILE} unchanged`);
    writeFileSync(new URL(STORES_MODULE, `file://${root}`), storesModule(next));
    spawnSync("npx", ["prettier", "--write", STORES_MODULE], {
      cwd: root,
      stdio: "ignore",
    });
    const url = new URL(COVERAGE_PAGE, `file://${root}`);
    const page = readFileSync(url, "utf8");
    if (!pageStatesStores(page, next)) {
      writeFileSync(url, renderStores(page, next));
      spawnSync("npx", ["prettier", "--write", COVERAGE_PAGE], {
        cwd: root,
        stdio: "ignore",
      });
      console.log(`wrote ${COVERAGE_PAGE}`);
    }
  }
}
