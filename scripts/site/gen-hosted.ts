// Writes site/_data/hosted.json, what the hosted registry serves, from a built pack's manifest (what the Worker
// answers from, after withheld counties and entity scoping), then rewrites every place that states it: the
// marked spans and llms.txt lines of HOSTED_FILES (scripts/site/hosted.mjs). Only the small JSON and the text
// are written; the pack is only read.
//
//   node --experimental-strip-types --conditions=factlot-source scripts/site/gen-hosted.ts <pack dir>
//   node --experimental-strip-types --conditions=factlot-source scripts/site/gen-hosted.ts --text   (from hosted.json)
//   node --experimental-strip-types --conditions=factlot-source scripts/site/gen-hosted.ts --check  (fail if out of date)
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { ANONYMOUS_REGISTRY_LOOKUPS_PER_DAY } from "../../deploy/cloudflare/src/plans.ts";
import type { Manifest } from "../../deploy/registry/src/format.ts";
import { countyName } from "../../packages/tools/src/county_names.ts";

import { FIELDS_DATA, fieldsData, writeFieldsData } from "./gen-fields.ts";
import {
  DATA_FILE as MCP_DATA_FILE,
  mcpDataCurrent,
  writeResourceData,
} from "../mcp/gen-resources.ts";
import {
  HOSTED_FILES,
  groupPlaces,
  hostedDifferences,
  placesText,
  renderHosted,
  totalsText,
  withheldText,
} from "./hosted.mjs";

const root = fileURLToPath(new URL("../../", import.meta.url));
const DATA = "site/_data/hosted.json";
/** The Worker's account page states the hosted regions from this generated module (it cannot read site/_data). */
export const NOTE_FILE = "deploy/cloudflare/src/hosted_note.ts";

export interface HostedCounty {
  fips: string;
  name: string;
  state: string;
  parcels: number;
  buildings: number;
  as_of: string;
  sources: string[];
}

export interface HostedData {
  about: string;
  pack_built_at: string;
  totals: {
    parcels: number;
    counties: number;
    buildings: number;
    entities: number;
    states: string[];
  };
  places: {
    key: string;
    counties: string[];
    names: string[];
    parcels: number;
    buildings: number;
    as_of: string;
  }[];
  counties: HostedCounty[];
  /** The order the Texas pages list the hosted Texas counties (site/_data/texas-counties.json). */
  texas_order: string[];
  /** Entity registries: entities served, and for one served in part, the registry's total. */
  entity_registries: {
    jurisdiction: string;
    entities: number;
    total?: number;
  }[];
  withheld: { fips: string; name: string; state: string }[];
  partial: { fips: string; area: string }[];
  /** The sentences hosted.mjs renders, for readers that do not run it (gen_coverage_docs.py). */
  text?: { places: string; totals: string; withheld: string };
}

/** The sentences of `text`, from the rest of the data. */
export function hostedText(data: HostedData): NonNullable<HostedData["text"]> {
  return {
    places: placesText(data),
    totals: totalsText(data),
    withheld: withheldText(data),
  };
}

/** hosted.json's content from a pack manifest. */
export function hostedData(m: Manifest, texasOrder: string[]): HostedData {
  const cov = m.coverage;
  const counties: HostedCounty[] = cov.counties.map((c) => {
    const fips = `${c.state_fips}${c.county_fips}`;
    return {
      fips,
      name: countyName(fips) ?? `county ${fips}`,
      state: c.state ?? `state ${c.state_fips}`,
      parcels: c.parcels,
      buildings: c.buildings,
      as_of: c.sources.reduce((a, s) => (s.as_of > a ? s.as_of : a), ""),
      sources: c.sources.map((s) => s.source_id),
    };
  });
  const stateOf = (fips: string) =>
    cov.counties.find((c) => c.state_fips === fips.slice(0, 2))?.state ?? null;
  return {
    about:
      "What the hosted registry serves, generated by scripts/site/gen-hosted.ts from the manifest of the pack it answers from. The pages and llms.txt state these figures; site.test.ts checks them.",
    pack_built_at: m.built_at,
    totals: {
      parcels: cov.totals.parcels,
      counties: cov.totals.counties,
      buildings: cov.totals.buildings,
      entities: cov.totals.entities,
      states: cov.totals.states,
    },
    places: groupPlaces(counties),
    counties,
    texas_order: texasOrder,
    entity_registries: cov.entity_registries.map((r) => {
      const s = m.entity_scope?.[r.jurisdiction];
      return s
        ? { jurisdiction: r.jurisdiction, entities: r.entities, total: s.total }
        : { jurisdiction: r.jurisdiction, entities: r.entities };
    }),
    withheld: Object.keys(m.withheld ?? {})
      .sort()
      .map((fips) => ({
        fips,
        name: countyName(fips) ?? `county ${fips}`,
        state: stateOf(fips) ?? fips.slice(0, 2),
      })),
    partial: Object.entries(m.partial_counties ?? {})
      .sort()
      .map(([fips, p]) => ({ fips, area: p.area })),
  };
}

/** The text of NOTE_FILE: the sentence the account page's "Hosted regions" panel shows. */
export function noteSource(data: HostedData): string {
  const note = [`Hosted regions: ${placesText(data)}.`, withheldText(data)]
    .filter(Boolean)
    .join(" ");
  return `// Generated by scripts/site/gen-hosted.ts from site/_data/hosted.json; do not edit.\nexport const HOSTED_NOTE = ${JSON.stringify(note)};\n`;
}

function writeNote(data: HostedData): void {
  writeFileSync(join(root, NOTE_FILE), noteSource(data));
  spawnSync("npx", ["prettier", "--write", NOTE_FILE], {
    cwd: root,
    stdio: "ignore",
  });
}

function writeData(data: HostedData): void {
  writeFileSync(join(root, DATA), `${JSON.stringify(data, null, 2)}\n`);
  spawnSync("npx", ["prettier", "--write", DATA], {
    cwd: root,
    stdio: "ignore",
  });
}

async function main(argv: string[]): Promise<void> {
  const check = argv.includes("--check");
  const textOnly = argv.includes("--text");
  const packDir = argv.find((a) => !a.startsWith("--"));
  if (!check && !textOnly && !packDir) {
    console.error(
      "usage: gen-hosted.ts <pack dir> | --text | --check  (see the comment at the top)",
    );
    process.exit(2);
  }
  let data: HostedData;
  if (packDir) {
    const m = JSON.parse(
      readFileSync(join(packDir, "manifest.json"), "utf8"),
    ) as Manifest;
    const texas = (
      JSON.parse(
        readFileSync(join(root, "site/_data/texas-counties.json"), "utf8"),
      ) as { counties: { name: string }[] }
    ).counties.map((c) => c.name);
    data = hostedData(m, texas);
    data.text = hostedText(data);
    if (!check) {
      writeData(data);
      console.log(
        `${DATA}: ${data.totals.parcels} parcels in ${data.totals.counties} counties, ${data.places.length} places`,
      );
      // A pack built since the manifest carries field availability gives fields.json too; for an older pack, run
      // gen-fields.ts on the registry files it was built from.
      if (m.fields) {
        writeFieldsData(fieldsData(Object.values(m.fields), data));
        console.log(`${FIELDS_DATA}: from the manifest`);
      } else
        console.log(
          `${FIELDS_DATA}: the manifest has no field availability; run scripts/site/gen-fields.ts on the pack's registry files`,
        );
    }
  } else {
    data = JSON.parse(readFileSync(join(root, DATA), "utf8")) as HostedData;
    const text = hostedText(data);
    if (JSON.stringify(text) !== JSON.stringify(data.text)) {
      if (check) {
        console.error(`${DATA}: its "text" is out of date; run with --text`);
        process.exit(1);
      }
      data.text = text;
      writeData(data);
    }
  }
  const changed: string[] = [];
  const problems: string[] = [];
  if (check) {
    const want = noteSource(data).replace(/\s+/g, " ");
    const have = readFileSync(join(root, NOTE_FILE), "utf8").replace(
      /\s+/g,
      " ",
    );
    if (want !== have) problems.push(`${NOTE_FILE}: out of date`);
    if (!(await mcpDataCurrent()))
      problems.push(`${MCP_DATA_FILE}: out of date`);
  } else {
    writeNote(data);
    // The MCP server's factlot:// resources carry the same figures (scripts/mcp/gen-resources.ts).
    writeResourceData();
  }
  for (const rel of HOSTED_FILES) {
    const text = readFileSync(join(root, rel), "utf8");
    if (check) {
      for (const d of hostedDifferences(
        text,
        data,
        ANONYMOUS_REGISTRY_LOOKUPS_PER_DAY,
      ))
        problems.push(`${rel}: ${d}`);
      continue;
    }
    const r = renderHosted(text, data, ANONYMOUS_REGISTRY_LOOKUPS_PER_DAY);
    if (!r.found) problems.push(`${rel}: no hosted text marked`);
    if (r.text !== text) {
      writeFileSync(join(root, rel), r.text);
      changed.push(rel);
    }
  }
  if (changed.length) {
    spawnSync(
      "npx",
      ["prettier", "--write", ...changed.filter((f) => /\.(html|md)$/.test(f))],
      {
        cwd: root,
        stdio: "inherit",
      },
    );
    console.log(`rewrote ${changed.join(", ")}`);
  }
  if (problems.length) {
    console.error(problems.join("\n"));
    process.exit(1);
  }
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
)
  await main(process.argv.slice(2));
