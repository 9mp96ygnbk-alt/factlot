// Writes site/_data/markets.json: what the market pages (/new-york-city/, /los-angeles/, /san-francisco/,
// /boston/, /denver/, /connecticut/) say about each source and its example, read from the built registry files
// (opened read-only; the pack is built from the same files) with the tools' own answers. Counts, as-of dates
// and totals are not here: the pages take them from site/_data/hosted.json. No owner or other personal name
// is read into the file; owners are only tested for existence.
//
//   node --experimental-strip-types --conditions=factlot-source scripts/site/gen-markets.ts <dir with ny.db ca.db ma.db co.db ct.db>
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

import {
  configureRegistry,
  registryGet,
  registrySearchAddress,
} from "../../packages/tools/src/registry.ts";

import { MARKETS } from "./market-pages.mjs";

type Row = Record<string, unknown>;
interface Db {
  prepare(sql: string): { all(...a: unknown[]): Row[] };
  close(): void;
}

const dir = process.argv[2];
if (!dir) throw new Error("usage: gen-markets.ts <dir with ny.db ca.db ...>");
const root = new URL("../../", import.meta.url);
const { DatabaseSync } = createRequire(import.meta.url)("node:sqlite") as {
  DatabaseSync: new (p: string, o: { readOnly: boolean }) => Db;
};

const exists = (db: Db, predicate: string, prefix: string): boolean =>
  db
    .prepare(
      "SELECT 1 AS x FROM facts WHERE predicate = ? AND subject >= ? AND subject < ? LIMIT 1",
    )
    .all(predicate, prefix, `${prefix}\uffff`).length > 0;

const markets = MARKETS.map((m) => {
  const path = join(dir, `${m.db}.db`);
  const db = new DatabaseSync(path, { readOnly: true });
  const sources = m.sources.map((id) => {
    const s = db
      .prepare(
        "SELECT source_id, publisher, title, url, license, ai_use, redistribution, attribution, terms_reviewed FROM sources WHERE source_id = ?",
      )
      .all(id)[0];
    if (!s) throw new Error(`${m.slug}: no source ${id} in ${path}`);
    return s;
  });
  configureRegistry(path);
  const found = registrySearchAddress(m.sample, 5);
  const hit = found.find((r) => String(r.urn).startsWith(m.sampleUrnPrefix));
  if (!hit) throw new Error(`${m.slug}: "${m.sample}" finds no parcel`);
  const record = registryGet(String(hit.urn)) as {
    label: string;
    facts: { predicate: string; value: unknown; unit?: string }[];
    value_history?: Record<string, unknown>[];
  };
  const id = db
    .prepare("SELECT system, external_id FROM crosswalk WHERE urn = ?")
    .all(hit.urn)[0];
  if (!id) throw new Error(`${m.slug}: no crosswalk row for ${hit.urn}`);
  const latest = record.value_history?.[0] ?? {};
  const out = {
    slug: m.slug,
    sources,
    id_system: String(id.system),
    sample: {
      query: m.sample,
      matches: found.length,
      urn: String(hit.urn),
      label: record.label,
      external_id: String(id.external_id),
      tax_year: latest.tax_year ?? null,
      market_value: latest.market_value ?? null,
      appraised_value: latest.appraised_value ?? null,
      predicates: [...new Set(record.facts.map((f) => f.predicate))].sort(),
    },
    holds: {
      owner_of_record: exists(
        db,
        "ownership.owner_of_record",
        m.sampleUrnPrefix,
      ),
      zoning: exists(db, "zoning.district", m.sampleUrnPrefix),
    },
  };
  db.close();
  return out;
});
configureRegistry(undefined);

writeFileSync(
  new URL("site/_data/markets.json", root),
  `${JSON.stringify(
    {
      about:
        "What the market pages say about each source and its worked example, generated by scripts/site/gen-markets.ts from the built registry files. Counts and as-of dates come from hosted.json.",
      markets,
    },
    null,
    2,
  )}\n`,
);
console.log(
  markets
    .map((m) => `${m.slug}: ${m.sample.urn} owner=${m.holds.owner_of_record}`)
    .join("\n"),
);
