// Writes site/_data/plans.json, the plan facts the site states, from deploy/cloudflare/src/plans.ts (what the
// Worker enforces and /v1/plans serves). scripts/site/build.mjs fills the pricing, home, MCP and Try pages'
// {{PLAN_*}} placeholders from it. The documents that cannot be built (PLAN_FILES) hold the same two sentences,
// what needs a Pro or Team key and how a lookup is counted, between markers (<!-- plans:paid-only --> ...
// <!-- /plans:paid-only -->, <!-- plans:counted --> ... <!-- /plans:counted -->) or, in llms.txt, as whole
// lines; this script rewrites them, and site.test.ts fails when the JSON or any of them differs from plans.ts.
//
//   node --experimental-strip-types --conditions=factlot-source scripts/site/gen-plans.ts
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import {
  ANONYMOUS_REGISTRY_LOOKUPS_PER_DAY,
  ANONYMOUS_REQUESTS_PER_MINUTE,
  FREE_KEY_NOTE,
  PAID_ONLY,
  PLANS,
  PRICING_URL,
  PRO_YEARLY,
  QUOTA_RULES,
  REPORTS_PER_MONTH,
  paidOnlyText,
  publicPlans,
} from "../../deploy/cloudflare/src/plans.ts";

export const PLANS_DATA = "site/_data/plans.json";

/** The plan facts the site states, all taken from plans.ts. */
export function plansData() {
  const site = new URL(PRICING_URL).origin;
  const listed = publicPlans(site, true, true) as Record<
    string,
    Record<string, unknown>
  >;
  return {
    _about:
      "Generated by scripts/site/gen-plans.ts from deploy/cloudflare/src/plans.ts; do not edit. The checkout links are the ones GET /v1/plans gives.",
    free: {
      requests_per_minute: ANONYMOUS_REQUESTS_PER_MINUTE,
      registry_lookups_per_day: ANONYMOUS_REGISTRY_LOOKUPS_PER_DAY,
      reports_per_month: REPORTS_PER_MONTH.anonymous,
      free_key_note: FREE_KEY_NOTE,
    },
    paid: Object.values(PLANS).map((p) => ({
      id: p.id,
      usd_per_month: p.monthlyCents / 100,
      ...(p.id === PRO_YEARLY.plan
        ? { usd_per_year: PRO_YEARLY.cents / 100 }
        : {}),
      requests_per_minute: p.requestsPerMinute,
      registry_lookups_per_month: p.registryLookupsPerMonth,
      keys: p.maxKeys,
      reports_per_month: REPORTS_PER_MONTH[p.id],
    })),
    checkout: {
      pro: String(listed.pro!.checkout),
      pro_yearly: String(listed.pro!.checkout_yearly),
      team: String(listed.team!.checkout),
    },
    paid_only: PAID_ONLY.map((f) => ({
      id: f.id,
      what: f.what,
      free: f.free,
      tools: [...f.tools],
      ...(f.arg ? { arg: f.arg } : {}),
    })),
    paid_only_text: paidOnlyText(),
    lookup_counted: QUOTA_RULES.counted,
  };
}

/** Each snake_case identifier (registry_get, as_of, registry_*) in backticks. */
export const markdownCode = (text: string) =>
  text.replace(
    /\bregistry_\*|\b[a-z][a-z0-9]*(?:_[a-z0-9]+)+\b/g,
    (m) => `\`${m}\``,
  );

/** The documents that state the two plan sentences by hand, kept current by renderPlans. */
export const PLAN_FILES = [
  "README.md",
  "docs/getting-started.md",
  "docs/agents.md",
  "llms.txt",
  "site/llms.txt",
];

const SPANS = {
  "paid-only": () => markdownCode(paidOnlyText()),
  counted: () => markdownCode(QUOTA_RULES.counted),
};
/** llms.txt states each sentence as one list item, found by how it starts. */
const LINES: Record<keyof typeof SPANS, RegExp> = {
  "paid-only": /^- \w+ things on the hosted API need a Pro or Team key: .*$/gm,
  counted: /^- A lookup is one answered call to a .*$/gm,
};

/** `text` with every plan sentence it holds rewritten from plans.ts, and how many it holds. */
export function renderPlans(text: string): { text: string; found: number } {
  let found = 0;
  let out = text;
  for (const [id, render] of Object.entries(SPANS)) {
    out = out.replace(
      new RegExp(
        `(<!-- plans:${id} -->)[\\s\\S]*?(<!-- /plans:${id} -->)`,
        "g",
      ),
      (_m, open: string, close: string) => {
        found++;
        return `${open}${render()}${close}`;
      },
    );
    out = out.replace(LINES[id as keyof typeof SPANS], () => {
      found++;
      return `- ${render()}`;
    });
  }
  return { text: out, found };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = fileURLToPath(new URL("../../", import.meta.url));
  for (const f of PLAN_FILES) {
    const before = readFileSync(`${root}${f}`, "utf8");
    const { text } = renderPlans(before);
    if (text !== before) {
      writeFileSync(`${root}${f}`, text);
      console.log(`rewrote ${f}`);
    }
  }
  writeFileSync(
    new URL(`../../${PLANS_DATA}`, import.meta.url),
    `${JSON.stringify(plansData(), null, 2)}\n`,
  );
  spawnSync("npx", ["prettier", "--write", PLANS_DATA], {
    cwd: fileURLToPath(new URL("../../", import.meta.url)),
    stdio: "ignore",
  });
  console.log(`wrote ${PLANS_DATA}`);
}
