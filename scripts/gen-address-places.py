"""Generate the city and ZIP code tables registry_search_address's misses use to name a county the registry does not hold.

    python3 scripts/gen-address-places.py [REGISTRY.db ...]

With registry files, rewrites spec/registry/address-places.tsv from the situs addresses of their parcels: for each
state, city and ZIP code a parcel label names, the counties (5-digit FIPS, from the parcel URNs) holding at least
MIN_PARCELS of its parcels and at least MIN_SHARE of them. Only the city or ZIP code and the county are kept, never
an address. Then writes the TypeScript and Python tables from the TSV; both are tested against it, so regenerate
rather than edit them.

A city is the last comma part of a label after its ZIP code and state ("1 MAIN ST, HOUSTON, TX 77002", "633 W 5TH ST,
LOS ANGELES CA 90071"): one to five words of letters. A label without a comma gives its ZIP code only. A ZIP code is
the 5 digits ending the label.
"""

from __future__ import annotations

import re
import sqlite3
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TSV = ROOT / "spec" / "registry" / "address-places.tsv"
TS_OUT = ROOT / "packages" / "tools" / "src" / "address_places.ts"
PY_OUT = ROOT / "python" / "src" / "factlot" / "registry" / "address_places.py"
MIN_PARCELS = 3
MIN_SHARE = 0.05

STATE_BY_FIPS = {
    "01": "AL", "02": "AK", "04": "AZ", "05": "AR", "06": "CA", "08": "CO", "09": "CT", "10": "DE", "11": "DC",
    "12": "FL", "13": "GA", "15": "HI", "16": "ID", "17": "IL", "18": "IN", "19": "IA", "20": "KS", "21": "KY",
    "22": "LA", "23": "ME", "24": "MD", "25": "MA", "26": "MI", "27": "MN", "28": "MS", "29": "MO", "30": "MT",
    "31": "NE", "32": "NV", "33": "NH", "34": "NJ", "35": "NM", "36": "NY", "37": "NC", "38": "ND", "39": "OH",
    "40": "OK", "41": "OR", "42": "PA", "44": "RI", "45": "SC", "46": "SD", "47": "TN", "48": "TX", "49": "UT",
    "50": "VT", "51": "VA", "53": "WA", "54": "WV", "55": "WI", "56": "WY", "72": "PR",
}
_WORDS = re.compile(r"[^A-Z0-9]+")
_ZIP_AFTER_COMMA = re.compile(r"(?:^|[^0-9A-Z_])([0-9]{5})(?:[- ]?[0-9]{1,4})?\s*$")
_STATE_ZIP_TAIL = re.compile(r"\s[A-Z]{2}\s+([0-9]{5})(?:[- ]?[0-9]{1,4})?\s*$")


def label_zip(label: str) -> str | None:
    s = label.upper().strip()
    m = _ZIP_AFTER_COMMA.search(s.split(",", 1)[1]) if "," in s else _STATE_ZIP_TAIL.search(s)
    return m.group(1) if m else None


def label_city(label: str) -> str | None:
    s = label.upper()
    if "," not in s:
        return None
    parts = [w for w in ([x for x in _WORDS.split(p) if x] for p in s.split(",")[1:]) if w]
    while parts and parts[-1][-1].isdigit():
        parts[-1].pop()
        if not parts[-1]:
            parts.pop()
    if parts and parts[-1][-1] in STATE_BY_FIPS.values():
        parts[-1].pop()
        if not parts[-1]:
            parts.pop()
    w = parts[-1] if parts else []
    if not w or len(w) > 5 or not all(re.fullmatch(r"[A-Z]+", x) for x in w):
        return None
    return " ".join(w)


def write_tsv(dbs: list[str]) -> None:
    counts: dict[tuple[str, str], Counter] = defaultdict(Counter)
    for path in dbs:
        db = sqlite3.connect(f"file:{path}?immutable=1", uri=True)
        for urn, label in db.execute("SELECT urn, label FROM subjects WHERE kind = 'parcel' AND label IS NOT NULL"):
            m = re.match(r"fl:parcel:us-([0-9]{2})([0-9]{3}):", urn)
            if not m or m.group(1) not in STATE_BY_FIPS:
                continue
            st, county = STATE_BY_FIPS[m.group(1)], m.group(1) + m.group(2)
            for key in (label_city(label), label_zip(label)):
                if key:
                    counts[(st, key)][county] += 1
        db.close()
    rows = []
    for (st, key), c in sorted(counts.items()):
        total = sum(c.values())
        kept = sorted(f for f, n in c.items() if n >= MIN_PARCELS and n / total >= MIN_SHARE)
        if kept:
            rows.append(f"{st}\t{key}\t{' '.join(kept)}")
    names = ", ".join("/".join(Path(d).parts[-2:]) for d in dbs)
    head = ("# Counties holding the parcels of each city and ZIP code that registry parcel labels name "
            "(scripts/gen-address-places.py): state, city or ZIP code, 5-digit county FIPS codes.\n"
            f"# Built from {len(dbs)} registry files ({names}); a county is kept with at least {MIN_PARCELS} of the "
            f"place's parcels and {MIN_SHARE:.0%} of them.\n")
    TSV.write_text(head + "\n".join(rows) + "\n", "utf-8")


def write_tables() -> None:
    lines = [ln for ln in TSV.read_text("utf-8").splitlines() if ln and not ln.startswith("#")]
    body = "\n".join(lines)
    ts = ("// Generated by scripts/gen-address-places.py from spec/registry/address-places.tsv; do not edit.\n"
          "// Counties holding the parcels of each city and ZIP code registry parcel labels name.\n\n"
          "// Lines of state, city or ZIP code, and space-separated 5-digit county FIPS codes, tab-separated.\n"
          f"const DATA = {_js_string(body)};\n\n"
          "let table: Map<string, string[]> | undefined;\n\n"
          "/** The counties (5-digit FIPS) holding a city's or ZIP code's parcels in a state, or null when the table "
          "does not know it (`place_counties` in Python). */\n"
          "export function placeCounties(state: string, place: string): string[] | null {\n"
          "  if (!table) {\n"
          "    table = new Map();\n"
          "    for (const line of DATA.split(\"\\n\")) {\n"
          "      const [st, key, counties] = line.split(\"\\t\");\n"
          "      table.set(`${st}|${key}`, counties!.split(\" \"));\n"
          "    }\n"
          "  }\n"
          "  return table.get(`${state}|${place}`) ?? null;\n"
          "}\n")
    TS_OUT.write_text(ts, "utf-8")
    py = ('"""Counties holding the parcels of each city and ZIP code registry parcel labels name.\n\n'
          'Generated by scripts/gen-address-places.py from spec/registry/address-places.tsv; do not edit.\n"""\n\n'
          "from __future__ import annotations\n\n"
          f"_DATA = {_py_string(body)}\n\n"
          "_TABLE: dict[str, list[str]] | None = None\n\n\n"
          "def place_counties(state: str, place: str) -> list[str] | None:\n"
          '    """The counties (5-digit FIPS) holding a city\'s or ZIP code\'s parcels in a state, or None when the table '
          'does not know it\n    (``placeCounties`` in TypeScript)."""\n'
          "    global _TABLE\n"
          "    if _TABLE is None:\n"
          "        _TABLE = {}\n"
          '        for line in _DATA.split("\\n"):\n'
          '            st, key, counties = line.split("\\t")\n'
          '            _TABLE[f"{st}|{key}"] = counties.split(" ")\n'
          '    return _TABLE.get(f"{state}|{place}")\n')
    PY_OUT.write_text(py, "utf-8")


def _js_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t") + '"'


def _py_string(s: str) -> str:
    lines = s.split("\n")
    return "(\n" + "\n".join(f'    "{ln.replace(chr(92), chr(92) * 2).replace(chr(34), chr(92) + chr(34)).replace(chr(9), chr(92) + "t")}\\n"'
                              for ln in lines[:-1]) + (
        f'\n    "{lines[-1].replace(chr(9), chr(92) + "t")}"\n)' if lines else '""')


if __name__ == "__main__":
    if len(sys.argv) > 1:
        write_tsv(sys.argv[1:])
    write_tables()
