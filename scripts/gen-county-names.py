"""Generate the county-name tables the registry's coverage messages use.

    python3 scripts/gen-county-names.py [national_county2020.txt]

With the Census file, rewrites spec/registry/county-names.tsv from it (the file's own copy in the
repo, with its source and date). Then writes the TypeScript and Python tables from the TSV. Both
tables are tested against the TSV, so regenerate rather than edit them.

Source: US Census Bureau, "2020 Census FIPS Codes for Counties and County Equivalents"
(https://www2.census.gov/geo/docs/reference/codes2020/national_county2020.txt), a work of the US
government and in the public domain. Columns used: STATEFP, COUNTYFP, COUNTYNAME.
"""

from __future__ import annotations

import hashlib
import sys
from collections import defaultdict
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TSV = ROOT / "spec" / "registry" / "county-names.tsv"
TS_OUT = ROOT / "packages" / "tools" / "src" / "county_names.ts"
PY_OUT = ROOT / "python" / "src" / "factlot" / "registry" / "county_names.py"
URL = "https://www2.census.gov/geo/docs/reference/codes2020/national_county2020.txt"
TITLE = "US Census Bureau, 2020 Census FIPS Codes for Counties and County Equivalents (national_county2020.txt)"


def write_tsv(census: Path) -> None:
    raw = census.read_bytes()
    lines = raw.decode("utf-8").splitlines()
    header = lines[0].split("|")
    col = {name: i for i, name in enumerate(header)}
    rows = []
    for line in lines[1:]:
        f = line.split("|")
        fips = f[col["STATEFP"]] + f[col["COUNTYFP"]]
        name = f[col["COUNTYNAME"]]
        assert len(fips) == 5 and fips.isdigit() and name and "\t" not in name and "|" not in name, line
        rows.append((fips, name))
    rows.sort()
    out = [
        f"# County names by 5-digit FIPS code (state + county). Source: {TITLE},",
        f"# {URL}",
        "# A work of the US government, in the public domain.",
        f"# Retrieved {date.today().isoformat()}; sha256 {hashlib.sha256(raw).hexdigest()}; {len(rows)} rows.",
        "# Columns: fips, name. Regenerate with scripts/gen-county-names.py.",
    ] + [f"{fips}\t{name}" for fips, name in rows]
    TSV.write_text("\n".join(out) + "\n", encoding="utf-8")


def read_tsv() -> tuple[list[str], list[tuple[str, str]]]:
    comments, rows = [], []
    for line in TSV.read_text(encoding="utf-8").splitlines():
        if line.startswith("#"):
            comments.append(line[2:])
        elif line:
            fips, name = line.split("\t")
            rows.append((fips, name))
    return comments, rows


def by_state(rows: list[tuple[str, str]]) -> dict[str, str]:
    """One string per state: the 3-digit county code and the name, entries separated by '|'."""
    out: dict[str, list[str]] = defaultdict(list)
    for fips, name in rows:
        out[fips[:2]].append(fips[2:] + name)
    return {st: "|".join(v) for st, v in sorted(out.items())}


def main() -> None:
    if len(sys.argv) > 1:
        write_tsv(Path(sys.argv[1]))
    comments, rows = read_tsv()
    retrieved = next(c for c in comments if c.startswith("Retrieved ")).split(";")[0][len("Retrieved "):]
    source = f"{TITLE}, {URL}; public domain; retrieved {retrieved}"
    states = by_state(rows)
    ts = [
        "// Generated by scripts/gen-county-names.py from spec/registry/county-names.tsv; do not edit.",
        *[f"// {c}" for c in comments[:4]],
        "",
        "/** Where the county names come from (`county_names.SOURCE` in Python). */",
        f"export const COUNTY_NAMES_SOURCE =\n  {json_str(source)};",
        "",
        "// Per state FIPS: 3-digit county code and name, entries separated by '|'.",
        "const BY_STATE: Record<string, string> = {",
        *[f"  {json_str(st)}: {json_str(v)}," for st, v in states.items()],
        "};",
        "",
        "let table: Map<string, string> | undefined;",
        "",
        '/** The Census name of a county ("Pinal County") by 5-digit FIPS code, or undefined. */',
        "export function countyName(fips: string): string | undefined {",
        "  if (!table) {",
        "    table = new Map();",
        "    for (const [st, entries] of Object.entries(BY_STATE))",
        '      for (const e of entries.split("|"))',
        "        table.set(st + e.slice(0, 3), e.slice(3));",
        "  }",
        "  return table.get(fips);",
        "}",
        "",
    ]
    TS_OUT.write_text("\n".join(ts), encoding="utf-8")
    py = [
        '"""County names by 5-digit FIPS code, for the registry\'s coverage messages.',
        "",
        "Generated by scripts/gen-county-names.py from spec/registry/county-names.tsv; do not edit.",
        *comments[:4],
        '"""',
        "",
        "from __future__ import annotations",
        "",
        f"SOURCE = {json_str(source)}",
        "",
        "# Per state FIPS: 3-digit county code and name, entries separated by '|'.",
        "_BY_STATE = {",
        *[f"    {json_str(st)}: (\n        {json_str(v)}\n    )," for st, v in states.items()],
        "}",
        "_TABLE = {st + e[:3]: e[3:] for st, entries in _BY_STATE.items() for e in entries.split(\"|\")}",
        "",
        "",
        "def county_name(fips: str) -> str | None:",
        '    """The Census name of a county ("Pinal County") by 5-digit FIPS code, or None."""',
        "    return _TABLE.get(fips)",
        "",
    ]
    PY_OUT.write_text("\n".join(py), encoding="utf-8")
    print(f"{len(rows)} counties -> {TS_OUT.relative_to(ROOT)}, {PY_OUT.relative_to(ROOT)}")


def json_str(s: str) -> str:
    import json

    return json.dumps(s, ensure_ascii=False)


if __name__ == "__main__":
    main()
