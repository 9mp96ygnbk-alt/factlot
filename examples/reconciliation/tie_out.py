def hand_year3_difference() -> tuple[float, float]:
    """Year 3 potential base rent and recoveries, FactLot − the rounded model, by hand.

    Suite 100's lease expires at month 30; the blended lease starts in month 31 (year 3) at
    33 × 1.03² × (0.55 × 0.95 + 0.45) $/SF/yr. FactLot collects 1 − 0.45 = 55% of that first month's rent
    and recoveries, the rounded model 100%: the difference is −0.45 × one month. Recoveries: NNN, 12,000 SF ×
    10.25 × 1.03² ÷ 12 a month.
    """
    psf = 33 * 1.03 ** 2 * (0.55 * 0.95 + 0.45)
    rent_month = 12000 * psf / 12
    rec_month = 12000 * 10.25 * 1.03 ** 2 / 12
    return round(-0.45 * rent_month, 2), round(-0.45 * rec_month, 2)


def build() -> tuple[dict[str, bytes], dict[str, dict]]:
    """Every file to write (path relative to the repo root -> bytes) and the two vector files."""
    files: dict[str, bytes] = {}
    rel = os.path.relpath(OUT, ROOT)
    files[f"{rel}/dcf-input.json"] = (json.dumps(DCF, indent=2) + "\n").encode()
    files[f"{rel}/cam-input.json"] = (json.dumps(CAM, indent=2) + "\n").encode()
    files[f"{rel}/cam-input-defaults.json"] = (json.dumps(cam_defaults_input(), indent=2) + "\n").encode()
    exports = dcf_exports()
    other_totals = {}
    for stem, fmt, *_ in DCF_CASES:
        table, totals = exports[stem]
        other_totals[stem] = totals
        if fmt == "csv":
            files[f"{rel}/{stem}.csv"] = csv_text(table).encode()
        else:
            parts = xlsx_parts(table)
            files[f"{rel}/{stem}.xlsx"] = _zip(parts)
    cams = cam_exports()
    for stem, *_ in CAM_CASES:
        files[f"{rel}/{stem}.csv"] = cam_csv(cams[stem]).encode()
    manifest = {
        "notice": NOTICE.lstrip("# "),
        "dcf_input": "dcf-input.json",
        "dcf": [{"file": f"{stem}.{fmt}", "other_system": what, "other_totals": other_totals[stem],
                 "planted_causes": {**lines, **totals}} for stem, fmt, what, lines, totals in DCF_CASES],
        "cam": [{"file": f"{stem}.csv", "cam_input": inp, "other_system": what, "planted_causes": by_tenant,
                 "building_causes": building} for stem, inp, what, by_tenant, building in CAM_CASES],
    }
    files[f"{rel}/cases.json"] = (json.dumps(manifest, indent=2, ensure_ascii=False) + "\n").encode()

    # Read every export back the way a user would, run the tool, and check the planted cause.
    with tempfile.TemporaryDirectory() as tmp:
        for name, data in files.items():
            with open(os.path.join(tmp, os.path.basename(name)), "wb") as f:
                f.write(data)
        dcf_vectors = []
        for stem, fmt, what, lines, totals in DCF_CASES:
            got = lines_from_file(os.path.join(tmp, f"{stem}.{fmt}"))
            inp = {"dcf": DCF, "other": {"system": f"SYNTHETIC {stem}", "lines": got["lines"], **other_totals[stem]}}
            res = run("calc_reconcile_dcf", inp)["value"]
            expect: dict = {"value.all_within_tolerance": not lines and not totals,
                            "value.cells_compared": len(DCF_LINES) * (DCF["hold_years"] + 1)}
            idx = {x["line"]: i for i, x in enumerate(res["lines"])}
            tidx = {x["item"]: i for i, x in enumerate(res["totals"])}
            for line, c in lines.items():
                expect[f"value.lines.{idx[line]}.likely_causes.0.cause"] = c
            for item, c in totals.items():
                expect[f"value.totals.{tidx[item]}.likely_causes.0.cause"] = c
            if stem == "dcf-exact":
                expect["value.cells_outside_tolerance"] = 0
                expect["value.mapping.1.sign_flipped"] = True  # Free Rent shown positive
            if stem == "dcf-rounded-downtime":
                rent, rec = hand_year3_difference()
                expect[f"value.lines.{idx['potential_base_rent']}.likely_causes.0.years"] = [3, 6, 8]
                expect[f"value.lines.{idx['potential_base_rent']}.years.2.difference"] = rent
                expect[f"value.lines.{idx['expense_recoveries']}.years.2.difference"] = rec
            if stem == "dcf-mid-year":
                expect["value.cells_outside_tolerance"] = 0
                expect[f"value.totals.{tidx['unlevered_irr']}.within_tolerance"] = True
            _assert(res, expect, stem)
            dcf_vectors.append({"name": f"SYNTHETIC {stem}: {what}", "input": inp, "expect": expect, "tolerance": 0.01})
        cam_vectors = []
        for stem, cam_file, what, by_tenant, building in CAM_CASES:
            rows = cam_rows_from_file(os.path.join(tmp, f"{stem}.csv"))
            cam = json.loads(files[f"{rel}/{cam_file}"])
            inp = {"cam": cam, "other": {"system": f"SYNTHETIC {stem}", "pool": "CAM", "tenants": rows}}
            res = run("calc_reconcile_cam", inp)["value"]
            expect = {"value.all_within_tolerance": not by_tenant, "value.tenants_compared": 4}
            names = [x["tenant"] for x in res["tenants"]]
            for tenant, c in by_tenant.items():
                expect[f"value.tenants.{names.index(tenant)}.likely_causes.0.cause"] = c
            for i, c in enumerate(building):
                expect[f"value.building_causes.{i}.cause"] = c
            if stem == "cam-exact":
                expect["value.cells_outside_tolerance"] = 0
            if stem == "cam-admin-fee-before-cap":
                expect["value.tenants_within_tolerance"] = 3
            _assert(res, expect, stem)
            cam_vectors.append({"name": f"SYNTHETIC {stem}: {what}", "input": inp, "expect": expect})
    vectors = {
        "reconcile_dcf.json": {"calculator": "calc.reconcile_dcf", "version": 1, "notes": DCF_NOTES,
                               "cases": dcf_vectors + EXTRA_DCF},
        "reconcile_cam.json": {"calculator": "calc.reconcile_cam", "version": 1, "notes": CAM_NOTES,
                               "cases": cam_vectors + EXTRA_CAM},
    }
    return files, vectors


def _zip(parts: list[tuple[str, str]]) -> bytes:
    import zipfile

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for name, data in parts:
            info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, data)
    return buf.getvalue()


def _at(obj, path: str):
    for key in path.split("."):
        obj = obj[int(key)] if isinstance(obj, list) else obj.get(key)
    return obj


def _assert(res: dict, expect: dict, stem: str) -> None:
    for path, want in expect.items():
        got = _at({"value": res}, path)
        ok = abs(got - want) <= 0.01 if isinstance(want, float) else got == want
        if not ok:
            raise AssertionError(f"{stem}: {path} is {got!r}, expected {want!r}")


