def dcf_rows(dcf: dict) -> list[dict]:
    return run("calc_dcf_pro_forma", dcf)["value"]["cash_flows"]


def rounded_rollover_input() -> dict:
    """The DCF input with blended downtime and free rent rounded to whole months.

    Suite 100 (p = 0.55): downtime 0.45 → 0, free rent 0.55 × 1 + 0.45 × 3 = 1.9 → 2.
    The market leasing (p = 0.75, Suite 200): downtime 0.25 × 5 = 1.25 → 1 (a new-tenant downtime of 4
    gives exactly 1), free rent 0.75 × 1 + 0.25 × 4 = 1.75 → 2. Suite 300 is leased once for 120 months
    from vacant (no blend) and Suite 400 does not roll inside the projection, so nothing else changes.
    """
    d = copy.deepcopy(DCF)
    d["leases"][0]["leasing"].update(downtime_months=0, free_rent_months_new=2, free_rent_months_renewal=2)
    d["leases"][1]["leasing"] = {"downtime_months": 4, "free_rent_months_new": 2, "free_rent_months_renewal": 2}
    return d


def vacancy_on_pbr(rows: list[dict]) -> list[dict]:
    """General vacancy at 4% of potential base rent (FactLot: of gross revenue), carried to EGR, the
    management fee (3% of EGR), NOI and cash flow."""
    out = []
    for c in rows:
        vac = round_(-DCF["general_vacancy_rate"] * c["potential_base_rent"], 2)
        egr = round_(c["gross_revenue"] + vac + c["credit_loss"], 2)
        fee = round_(-DCF["management_fee_rate"] * egr, 2)
        noi = round_(egr + c["operating_expenses"] + fee, 2)
        cf = round_(noi + c["tenant_improvements"] + c["leasing_commissions"] + c["capital_reserves"], 2)
        out.append({**c, "general_vacancy": vac, "effective_gross_revenue": egr, "management_fee": fee,
                    "net_operating_income": noi, "cash_flow_before_debt": cf})
    return out


def annual_table(rows: list[dict], deductions_positive: bool) -> list[list]:
    years = len(rows)
    table: list[list] = [[NOTICE], ["Line", *[f"Year {y}" for y in range(1, years + 1)], "Total"]]
    for k in DCF_LINES:
        vals = [-c[k] if deductions_positive and k in DEDUCTIONS else c[k] for c in rows]
        vals = [0.0 if v == 0 else v for v in vals]
        table.append([LABELS[k], *vals, round_(sum(vals), 2)])
    return table


def csv_text(table: list[list]) -> str:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    for r in table:
        w.writerow([f"{c:.2f}" if isinstance(c, float) else c for c in r])
    return buf.getvalue()


def xlsx_parts(table: list[list]) -> list[tuple[str, str]]:
    wb = Workbook("SYNTHETIC annual cash flow export")
    sh = wb.sheet("Annual_Cash_Flow")
    for i, r in enumerate(table, start=1):
        for j, c in enumerate(r, start=1):
            sh.put(i, j, c, "text" if isinstance(c, str) else "money")
    sh.width(1, 34)
    wb.evaluate()
    return wb.parts()


