def main(argv: list[str]) -> int:
    EXTRA_DCF[:] = _small_cases()
    EXTRA_CAM[:] = _small_cam()
    files, vectors = build()
    for name, spec in vectors.items():
        files[os.path.relpath(os.path.join(VECTORS, name), ROOT)] = (json.dumps(spec, indent=2, ensure_ascii=False) + "\n").encode()
    check = "--check" in argv
    status = 0
    for name, data in sorted(files.items()):
        path = os.path.join(ROOT, name)
        if check:
            if not os.path.exists(path):
                print(f"MISSING  {name}")
                status = 1
            elif not _same(path, data):
                print(f"STALE    {name} (run examples/reconciliation/tie_out.py)")
                status = 1
        elif not (os.path.exists(path) and _same(path, data)):  # unchanged files keep their formatting
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "wb") as f:
                f.write(data)
    if status == 0:
        print(f"{'ok' if check else 'wrote'}     tie-out fixtures: {len(DCF_CASES)} DCF and {len(CAM_CASES)} CAM synthetic "
              f"exports, every planted cause named; {len(vectors)} vector files")
    return status


def _same(path: str, data: bytes) -> bool:
    with open(path, "rb") as f:
        disk = f.read()
    if path.endswith(".xlsx"):
        import zipfile

        def members(b: bytes) -> dict:
            with zipfile.ZipFile(io.BytesIO(b)) as z:
                return {n: z.read(n) for n in z.namelist()}

        return members(disk) == members(data)
    if path.endswith(".json"):
        # The repository formats JSON with prettier (npx prettier --write after writing); compare the content.
        return json.loads(disk) == json.loads(data)
    return disk == data


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
